"""Writes PREDICTIONS.md from v0.1 data only (data/epsilon_star.csv, data/class_summary.csv).

Sealed before any solver for the small-noise orders exists. The per-class predicted order
k_pred is read off the v0.1 trend: if rho ~ a * eps^k * log(1/eps), then
rho(0.002)/rho(0.001) -> 2^k * lambda(0.002)/lambda(0.001), so
k_pred = round(log2(ratio / (lambda(0.002)/lambda(0.001)))).
"""
import os, numpy as np, pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
es = pd.read_csv(os.path.join(ROOT, "data", "epsilon_star.csv"))
cs = pd.read_csv(os.path.join(ROOT, "data", "class_summary.csv"))
lam = lambda e: (1 - 2 * e) * np.log((1 - e) / e)
base = lam(0.002) / lam(0.001)
d = es.merge(cs[["rule", "rising", "trend_ratio"]], on="rule")
d["k_cont"] = np.log2(d.rho_ratio_0002_over_0001 / base)
d["k_pred"] = d.k_cont.round().astype(int)
d["v01"] = np.where(d.limit_type == "B_proved", "B", np.where(d.rising == 1, "U-rising", "U-falling"))
nB = (d.v01 == "B").sum(); nR = (d.v01 == "U-rising").sum(); nF = (d.v01 == "U-falling").sum()
kc = lambda s: ", ".join(f"k*={k}: {int(v)}" for k, v in s.value_counts().sort_index().items())
rows = "\n".join(
    f"| {r.rule} | {r.v01} | {r.rho_ratio_0002_over_0001:.4f} | {r.k_cont:.3f} | {r.k_pred} | "
    f"{'unresolved at 0.001/0.002 in v0.1' if r.smallest_resolved_eps > 0.001 else ''} |"
    for r in d.sort_values(["v01", "rule"]).itertuples())
amb = d[(d.k_cont - d.k_pred).abs() > 0.1].sort_values("rule")
amb_txt = ", ".join(f"{r.rule} ({r.k_cont:.2f})" for r in amb.itertuples())
rising_top = d[d.v01 == "U-rising"].sort_values("k_cont", ascending=False).head(4)
rt = ", ".join(f"{r.rule} (ratio {r.rho_ratio_0002_over_0001:.3f})" for r in rising_top.itertuples())
txt = f"""# PREDICTIONS (sealed before the solver)

Committed as the first commit of branch `noise-selected-cycles`, before any code that computes
stochastic potentials, resistances or small-noise orders exists. Generated by
`code/fw/make_predictions.py` from v0.1's `data/epsilon_star.csv` and `data/class_summary.csv`.

## Information available when writing

* v0.1 data files (n = 12): the trend ratios rho(0.002)/rho(0.001) per class, including the
  dense-solve values at the unresolved entries of rules 7, 23, 232 (and 19 at 0.001/0.002).
* A cycle-count scan (number of cycles of F for the 88 representatives at n = 12, 16, 20),
  done only to cost the computation; it does not compute anything about noise.
* Theory: for eps > 0 the chain is a regular perturbed Markov process with resistance
  r(x->y) = H(F(x), y); the order of pi_eps(x) is W(x) - min W (Markov chain tree theorem), and
  rho ~ c * eps^k* * log(1/eps) with k* = max_c min_{{x containing c}} ord pi_eps(x).

## Basis of the per-class prediction

If rho ~ a eps^k log(1/eps), the ratio rho(0.002)/rho(0.001) tends to 2^k * lambda(0.002)/lambda(0.001)
= 2^k * {base:.4f}. The v0.1 ratios cluster at this value times 1, 2, 4 and 8, so
k_pred = round(log2(ratio / {base:.4f})). The table below is that prediction; it is the claim to be
tested, not a result.

Distribution of k_pred: B classes ({nB}): {kc(d[d.v01=='B'].k_pred)}; U-falling ({nF}): {kc(d[d.v01=='U-falling'].k_pred)};
U-rising ({nR}): {kc(d[d.v01=='U-rising'].k_pred)}.

Classes where the continuous estimate is more than 0.1 from an integer (low confidence): {amb_txt}.

## Predictions

1. **Survival at n = 12.** All {nR} rising classes come out with k* = 0 (stochastically stable cycles
   cover all eight codes) and all {nF} falling U classes with k* >= 1: {nR}/{nR} and {nF}/{nF} survive.
   Confidence: about 75% that no class flips at all. If a rising class flips to k* >= 1, the most likely
   are the rising classes with the largest ratios: {rt}, in that order (a ratio above {base:.3f}
   means min_c nu_c still decreases with eps at 0.001, which an O(eps) leading term would also produce).
   Rule 41 is the single most likely flip.
2. **The four weak cases.** None of rules 7, 19, 23, 232 flips; all four have k* = 1 (the rarest code is
   010 or 101, created by one flip from a noise-selected fixed point; the v0.1 dense solutions at the
   unresolved entries already show min_c nu_c close to 6 eps).
3. **Orders.** k* equals k_pred in the table for every class with |k_cont - k_pred| <= 0.1. For rule
   200 (k_cont about 1.3) I predict k* = 1 with a large next-order coefficient (low confidence).
4. **B classes.** All 42 have k* >= 1 (this is v0.1's lemma; a violation would be a bug), with the
   distribution above.
5. **Dependence on n.** (a) The classes of rules 60 and 90 change with n: for n a power of two the
   global map is nilpotent over GF(2) (the only cycle is the all-zero state), so k* >= 1 at
   n = 4, 8, 16; for other n >= 5 their three-cell marginals are uniform and k* = 0. (b) Bijective
   rules (classes 15, 51, 170, 204) have k* = 0 at every n. (c) Parity of n changes the cycle sets
   (alternating patterns exist only for even n), and I expect a minority of classes (at most about
   10 of 88) to change between k* = 0 and k* >= 1 with the parity or divisibility of n, while at
   least 70 of 88 keep their n = 12 classification for every n >= 8. (d) Small rings (n = 4, 5, 6)
   deviate more often. (e) Where k* >= 1, its value is constant in n for most classes from n >= 8.
6. **Cost wall.** n = 20 is reachable for most classes; the classes with the most cycles at n = 20
   (rules 76, 29, 200, 108) are where the wall will be, if anywhere.

## Per-class predicted orders at n = 12

| rule | v0.1 type | rho(0.002)/rho(0.001) | k_cont | k_pred | note |
|---:|---|---:|---:|---:|---|
{rows}
"""
open(os.path.join(ROOT, "PREDICTIONS.md"), "w").write(txt)
print("written", len(d), "classes")
