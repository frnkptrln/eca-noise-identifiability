def codeset(cs):
    return "{" + ",".join(map(str, cs)) + "}" if cs else "{}"


def sel_cell(r):
    s = r["selected"]
    if s["orbits_complete"] and s["n_orbits"] <= 4:
        return "<br>".join("`%s` (T=%d, S=%d; t=%d, rot=%d)%s" % (
            o["rep"], o["temporal_period"], o["spatial_period"], o["t_rot"], o["rot"],
            "" if o["n_cycles_in_orbit"] == 1 else " x%d cycles" % o["n_cycles_in_orbit"]) for o in s["orbits"])
    agg = {}
    for t in s["type_summary"]:
        k = (t["temporal_period"], t["spatial_period"])
        agg[k] = agg.get(k, 0) + t["n_orbits"]
    items = sorted(agg.items())
    txt = ", ".join("(%d,%d)x%d" % (k[0], k[1], v) for k, v in items[:10])
    if len(items) > 10:
        txt += ", ... (+%d more (T,S) types)" % (len(items) - 10)
    first = ", ".join("`%s`" % o["rep"] for o in s["orbits"][:2])
    return "%d orbits by (T,S): %s<br>first reps: %s, ..." % (s["n_orbits"], txt, first)


def closed_cell(r):
    g = r["g1"]
    if g["n_closed_classes"] <= 6:
        return "%d: %s" % (g["n_closed_classes"], g["closed_class_sizes"])
    return "%d: " % g["n_closed_classes"] + ", ".join("size %d x%d" % (a, b) for a, b in g["closed_class_size_hist"])


