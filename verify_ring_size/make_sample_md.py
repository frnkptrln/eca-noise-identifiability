w("""- Ring of n cells, state x = x_0 x_1 ... x_(n-1), written as a bit string with x_0 first. A state is identified
  with the integer sum_i x_i 2^(n-1-i), i.e. the bit string read as a binary numeral (x_0 is the most significant
  bit). "Numerically smallest" always refers to this integer, which is the same as lexicographically smallest string.
- Rule number N: f(a,b,c) = bit (4a+2b+c) of N; (F x)_i = f(x_(i-1), x_i, x_(i+1)), indices mod n. The
  neighbourhood code at cell i is 4 x_(i-1) + 2 x_i + x_(i+1); "codes" are the integers 0..7.
- Noisy dynamics X_(t+1) = F(X_t) XOR Z_t, resistance r(x,y) = H(F(x), y). Cycles are the periodic orbits of F.
  R(u->v) = minimum total resistance of a path; V(C,C') = min over u in C, v in C' of R(u->v).
- gamma(C) = minimum total weight of a spanning in-tree on the set of cycles rooted at C, with weights V.
  A cycle is noise-selected iff gamma(C) = min gamma. k_c = min_C [gamma(C) + R(C->D_c)] - min gamma with D_c the
  set of states containing code c; k* = max_c k_c.
- G1: directed edge C -> C' (C != C') iff V(C,C') = 1. A closed class is a strongly connected component of G1
  with no edge leaving it (a cycle without outgoing G1 edge is a closed class of size one).
- Rotation sigma: (sigma x)_i = x_(i-1), i.e. the bit string rotated right by one place. A rotation orbit of
  cycles is {sigma^s C}. Its canonical representative ("rep") is the numerically smallest state over all states
  of the cycle and all their rotations.
- For a selected orbit: T = temporal period (cycle length); S = spatial period (smallest s > 0 with
  sigma^s x = x for its states); t = smallest t > 0 such that F^t(rep) is a rotation of rep; rot = smallest
  s >= 0 with F^t(rep) = sigma^s(rep) (so rot = 0 means t = T). "x k cycles" is the number of distinct cycles in
  the rotation orbit when it is larger than one.
- A single cycle is identified by its own numerically smallest state (no rotations); this is used for the members
  of closed classes. SHA-256 values are taken over the sorted bit strings joined by newline characters.
""")

w("## 3. Method\n")
w("""All code in this folder was written from the definitions above (`core.c`, `eca_core.py`, `solve.py`).

1. F is tabulated for all 2^n states; cycles and basins come from one pass over the functional graph.
2. R(C -> x) for a cycle C: since F(C) = C, R(C -> .) equals the shortest-path distance from the set C in the
   graph with arcs x -> F(x) of cost 0 and x -> x XOR e_i of cost 1 (a step x -> F(x) XOR z of resistance |z| is
   "apply F, then flip the cells of z one at a time"; conversely every state reached by such arcs from C is
   reached by noisy steps of the same total resistance, because every state of C has a preimage in C). This is
   computed by a 0-1 breadth-first search (Dial buckets) over all 2^n states.
3. V: one search per rotation orbit of cycles; the row is copied to the other cycles of the orbit by
   V(sigma C, sigma C') = V(C, C') (F commutes with sigma and H is rotation invariant). V is stored as a dense
   m x m byte matrix (m = number of cycles).
4. gamma for all roots at once from the definition: complete Edmonds contraction of the full cycle graph with
   weights V (every node picks its cheapest outgoing arc, loops of choices are contracted with reduced weights
   until one node is left); with rho(v) the reduced weight chosen by contraction-tree node v,
   gamma(C) = sum_v rho(v) - sum over the tree nodes v containing C of rho(v). The noise-selected cycles are the
   minimisers of gamma. Nothing about the selected set is inferred from G1.
5. k_c from the same searches (minimum distance to a state containing code c), all eight values.
6. G1 is built from the sparse description "C -> C' iff some state of C with one cell flipped lies in the basin
   of C'" and checked in every case against the dense matrix (number of entries V = 1 and V = 1 on every edge).
   Strongly connected components by scipy; closed classes are the components without leaving edge. The set of
   cycles that cannot reach the selected set is obtained by a reverse search on G1.
""")
